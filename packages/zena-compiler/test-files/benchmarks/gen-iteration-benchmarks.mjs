// Generator for the iteration compile-cost benchmark workloads.
//
// These workloads isolate the COMPILE-TIME cost of the three-arm `Step<V>`
// iterator protocol (docs/design/async-iteration.md) against the pre-flip
// boolean-tuple protocol and against plain array iteration. Each workload is a
// single entry point with N independent iteration sites; the benchmark runner
// (`npm run benchmark -w @zena-lang/zena-compiler -- --compiler --filter iter`) times how
// long the compiler takes on each, so the families can be compared and the
// growth with N inspected.
//
// Four families, chosen to answer *where* the cost is:
//   step-distinct  N sites, each iterating a DISTINCT element type, next(): Step<Ek>
//   step-same      N sites, all iterating the SAME element type,     next(): Step<i32>
//   bool           N sites, boolean-tuple protocol  next(): inline (true, Ek) | inline (false, _)
//   array          N sites, plain array `for`-in    (no protocol, direct index loop)
//
// Reading the results:
//   step-distinct >> bool ~= array  -> the Step protocol is the cost.
//   step-distinct >> step-same      -> cost is per DISTINCT type; memoizing
//                                      instantiations (dedup by (Step, T)) would help.
//   step-distinct ~= step-same, both >> bool -> cost is per SITE (target
//                                      substitution / Future materialization),
//                                      so memoization by type would NOT help and
//                                      the fix is to keep Future out of sync Step.
//   Compare a family across N (e.g. step-distinct-50 vs -150): if per-site cost
//   grows with N the cost accumulates (superlinear); if flat it is per-site.
//
// Regenerate (from packages/zena-compiler):
//   node test-files/benchmarks/gen-iteration-benchmarks.mjs
// or with custom sizes:
//   node test-files/benchmarks/gen-iteration-benchmarks.mjs 50 150 300

import {writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const outDir = dirname(fileURLToPath(import.meta.url));

const header = (family, n) =>
  `// GENERATED by gen-iteration-benchmarks.mjs — do not edit by hand.\n` +
  `// Family: ${family}, ${n} iteration sites. Measures compiler time only.\n` +
  `// See gen-iteration-benchmarks.mjs for what the families isolate.\n`;

const stepSite = (k, elem) => {
  const value = elem === 'i32' ? 'this.i' : `new ${elem}(this.i)`;
  const read = elem === 'i32' ? 'x' : 'x.v';
  return (
    (elem === 'i32' ? '' : `class ${elem}(v: i32)\n`) +
    `final class S${k} {\n` +
    `  var i: i32 = 0;\n` +
    `  new();\n` +
    `  next(): Step<${elem}> {\n` +
    `    if (this.i < 4) { this.i += 1; return (1, ${value}, _); }\n` +
    `    return (0, _, _);\n` +
    `  }\n` +
    `}\n` +
    `let drain${k} = (): i32 => {\n` +
    `  let s = new S${k}();\n` +
    `  var acc = 0;\n` +
    `  var run = true;\n` +
    `  while (run) {\n` +
    `    match (s.next()) {\n` +
    `      case (1, let x, _): { acc += ${read}; }\n` +
    `      case _: { run = false; }\n` +
    `    }\n` +
    `  }\n` +
    `  return acc;\n` +
    `};\n`
  );
};

const boolSite = (k) =>
  `class E${k}(v: i32)\n` +
  `final class B${k} {\n` +
  `  var i: i32 = 0;\n` +
  `  new();\n` +
  `  next(): inline (true, E${k}) | inline (false, _) {\n` +
  `    if (this.i < 4) { this.i += 1; return (true, new E${k}(this.i)); }\n` +
  `    return (false, _);\n` +
  `  }\n` +
  `}\n` +
  `let drain${k} = (): i32 => {\n` +
  `  let b = new B${k}();\n` +
  `  var acc = 0;\n` +
  `  while (let (true, x) = b.next()) { acc += x.v; }\n` +
  `  return acc;\n` +
  `};\n`;

const arraySite = (k) =>
  `class E${k}(v: i32)\n` +
  `let drain${k} = (): i32 => {\n` +
  `  let arr = [new E${k}(1), new E${k}(2), new E${k}(3)];\n` +
  `  var acc = 0;\n` +
  `  for (let x in arr) { acc += x.v; }\n` +
  `  return acc;\n` +
  `};\n`;

const mainFn = (n) => {
  let body = 'export let main = (): i32 => {\n  var t = 0;\n';
  for (let k = 0; k < n; k++) body += `  t += drain${k}();\n`;
  body += '  return t;\n};\n';
  return body;
};

const build = (family, n) => {
  const needsStep = family.startsWith('step');
  let src = header(family, n);
  if (needsStep) src += `import { Step } from 'zena:async';\n`;
  src += '\n';
  for (let k = 0; k < n; k++) {
    if (family === 'step-distinct') src += stepSite(k, `E${k}`);
    else if (family === 'step-same') src += stepSite(k, 'i32');
    else if (family === 'bool') src += boolSite(k);
    else if (family === 'array') src += arraySite(k);
    src += '\n';
  }
  src += mainFn(n);
  return src;
};

const sizes = process.argv.slice(2).map(Number).filter((n) => n > 0);
const big = sizes.length ? Math.max(...sizes) : 150;
const small = sizes.length ? Math.min(...sizes) : 50;

// step-distinct at two sizes (scaling), the other families at the big size.
const files = [
  ['step-distinct', small],
  ['step-distinct', big],
  ['step-same', big],
  ['bool', big],
  ['array', big],
];

for (const [family, n] of files) {
  const name = `iter-${family}-${n}.zena`;
  writeFileSync(join(outDir, name), build(family, n));
  console.log(`wrote ${name} (${n} sites)`);
}
